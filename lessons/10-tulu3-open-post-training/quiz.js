// Quiz state
let currentQuestion = 0;
let correctAnswers = 0;
let answeredQuestions = new Set();

// Initialize quiz
function initQuiz() {
    const container = document.getElementById('quiz-container');
    if (!container) return;
    
    displayQuestion();
}

// Display current question
function displayQuestion() {
    const container = document.getElementById('quiz-container');
    const question = quizQuestions[currentQuestion];
    const isAnswered = answeredQuestions.has(currentQuestion);
    
    let html = `
        <div class="quiz-question">
            <div class="question-header">
                <span class="question-number">Question ${currentQuestion + 1} of ${quizQuestions.length}</span>
                <span class="question-score">${correctAnswers} / ${answeredQuestions.size} correct</span>
            </div>
            <h3>${question.question}</h3>
            <div class="quiz-options">
    `;
    
    question.options.forEach((option, index) => {
        const optionId = `q${currentQuestion}_opt${index}`;
        html += `
            <div class="quiz-option ${isAnswered ? (index === question.correct ? 'correct' : '') : ''}" 
                 onclick="${isAnswered ? '' : `selectAnswer(${index})`}">
                <input type="radio" 
                       id="${optionId}" 
                       name="q${currentQuestion}" 
                       value="${index}"
                       ${isAnswered ? 'disabled' : ''}
                       ${isAnswered && index === question.correct ? 'checked' : ''}>
                <label for="${optionId}">${option}</label>
            </div>
        `;
    });
    
    html += `
            </div>
            <div id="feedback" class="quiz-feedback" style="display: none;"></div>
            <div class="quiz-navigation">
    `;
    
    if (currentQuestion > 0) {
        html += `<button class="btn" onclick="previousQuestion()">← Previous</button>`;
    }
    
    if (currentQuestion < quizQuestions.length - 1) {
        html += `<button class="btn" onclick="nextQuestion()">Next →</button>`;
    } else if (answeredQuestions.size === quizQuestions.length) {
        html += `<button class="btn" onclick="showSummary()">Finish Quiz</button>`;
    }
    
    html += `
            </div>
        </div>
    `;
    
    container.innerHTML = html;
    
    // Show feedback if already answered
    if (isAnswered) {
        showFeedback(question.correct);
    }
}

// Handle answer selection
function selectAnswer(selectedIndex) {
    const question = quizQuestions[currentQuestion];
    const isCorrect = selectedIndex === question.correct;
    
    if (isCorrect) {
        correctAnswers++;
    }
    
    answeredQuestions.add(currentQuestion);
    showFeedback(selectedIndex);
    
    // Update the display to show correct answer and disable options
    displayQuestion();
}

// Show feedback for selected answer
function showFeedback(selectedIndex) {
    const question = quizQuestions[currentQuestion];
    const isCorrect = selectedIndex === question.correct;
    const feedback = document.getElementById('feedback');
    
    if (!feedback) return;
    
    feedback.style.display = 'block';
    feedback.className = `quiz-feedback ${isCorrect ? 'correct' : 'incorrect'}`;
    feedback.innerHTML = `
        <strong>${isCorrect ? '✓ Correct!' : '✗ Incorrect'}</strong>
        <p>${question.explanation}</p>
    `;
}

// Navigation functions
function nextQuestion() {
    if (currentQuestion < quizQuestions.length - 1) {
        currentQuestion++;
        displayQuestion();
        window.scrollTo({ top: document.getElementById('quiz').offsetTop - 20, behavior: 'smooth' });
    }
}

function previousQuestion() {
    if (currentQuestion > 0) {
        currentQuestion--;
        displayQuestion();
        window.scrollTo({ top: document.getElementById('quiz').offsetTop - 20, behavior: 'smooth' });
    }
}

// Show final summary
function showSummary() {
    const container = document.getElementById('quiz-container');
    const summary = document.getElementById('quiz-summary');
    const scoreDisplay = document.getElementById('quiz-score');
    
    const percentage = Math.round((correctAnswers / quizQuestions.length) * 100);
    let message = '';
    
    if (percentage === 100) {
        message = 'Perfect score! You have an excellent understanding of Tülu 3\'s post-training pipeline.';
    } else if (percentage >= 80) {
        message = 'Great job! You have a strong grasp of open post-training techniques.';
    } else if (percentage >= 60) {
        message = 'Good effort! Review the lesson sections on RLVR and evaluation framework for deeper understanding.';
    } else {
        message = 'Keep learning! Revisit the sections on data curation, the multi-stage pipeline, and how each stage contributes to the final model.';
    }
    
    scoreDisplay.innerHTML = `
        <div class="score-circle">${correctAnswers}/${quizQuestions.length}</div>
        <div class="score-percentage">${percentage}%</div>
        <p>${message}</p>
    `;
    
    container.style.display = 'none';
    summary.style.display = 'block';
}

// Initialize quiz on page load
document.addEventListener('DOMContentLoaded', initQuiz);
